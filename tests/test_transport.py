from pathlib import Path

import httpx2
import pytest

from plain_client import Plain, Upload
from plain_client.base_model import UNSET
from plain_client.exceptions import (
    GraphQLClientGraphQLMultiError,
    GraphQLClientHttpError,
    GraphQLClientInvalidResponseError,
)


@pytest.mark.asyncio
async def test_default_client_and_cleanup() -> None:
    async with Plain(headers={"Authorization": "Bearer test"}) as client:
        assert isinstance(client.http_client, httpx2.AsyncClient)
        assert client.http_client.headers["Authorization"] == "Bearer test"
    assert client.http_client.is_closed


@pytest.mark.asyncio
async def test_json_request() -> None:
    async def handler(request: httpx2.Request) -> httpx2.Response:
        assert request.headers["Authorization"] == "Bearer test"
        assert request.headers["X-Test"] == "value"
        assert request.headers["Content-Type"] == "application/json"
        assert json.loads(request.content) == {
            "query": "query Example { value }",
            "operationName": "Example",
            "variables": {"null": None, "values": [1, 2]},
        }
        return httpx2.Response(200, json={"data": {"value": "ok"}})

    async with Plain(
        "https://test.app/graphql",
        http_client=httpx2.AsyncClient(
            transport=httpx2.MockTransport(handler),
            headers={"Authorization": "Bearer test"},
        ),
    ) as client:
        response = await client.execute(
            "query Example { value }",
            operation_name="Example",
            variables={"omitted": UNSET, "null": None, "values": [1, 2]},
            headers={"X-Test": "value"},
        )
        assert client.get_data(response) == {"value": "ok"}
    assert client.http_client.is_closed


@pytest.mark.asyncio
async def test_multipart_upload() -> None:
    async def handler(request: httpx2.Request) -> httpx2.Response:
        assert request.headers["Content-Type"].startswith("multipart/form-data;")
        body = (await request.aread()).decode()
        assert 'name="operations"' in body
        assert '"variables": {"files": [null, null]}' in body
        assert '"0": ["variables.files.0", "variables.files.1"]' in body
        assert body.count('filename="hello.txt"') == 1
        assert "hello world" in body
        return httpx2.Response(200, json={"data": {"uploaded": True}})

    async with Plain(
        "https://test.app/graphql",
        http_client=httpx2.AsyncClient(transport=httpx2.MockTransport(handler)),
    ) as client:
        upload = Upload("hello.txt", BytesIO(b"hello world"), "text/plain")
        response = await client.execute(
            "mutation Upload", variables={"files": [upload, upload]}
        )
        assert client.get_data(response) == {"uploaded": True}


@pytest.mark.asyncio
@pytest.mark.parametrize(
    ("response", "error"),
    [
        (httpx2.Response(503), GraphQLClientHttpError),
        (httpx2.Response(200, text="not json"), GraphQLClientInvalidResponseError),
        (httpx2.Response(200, json=[]), GraphQLClientInvalidResponseError),
        (httpx2.Response(200, json={}), GraphQLClientInvalidResponseError),
        (
            httpx2.Response(
                200, json={"data": {"partial": True}, "errors": [{"message": "denied"}]}
            ),
            GraphQLClientGraphQLMultiError,
        ),
    ],
)
async def test_response_errors(
    response: httpx2.Response, error: type[Exception]
) -> None:
    async with Plain() as client:
        with pytest.raises(error) as caught:
            client.get_data(response)
        if isinstance(caught.value, GraphQLClientGraphQLMultiError):
            assert caught.value.data == {"partial": True}
            assert caught.value.errors[0].message == "denied"
        else:
            assert isinstance(
                caught.value,
                (GraphQLClientHttpError, GraphQLClientInvalidResponseError),
            )
            assert caught.value.response is response


